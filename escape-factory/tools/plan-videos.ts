/**
 * VIDEO PLANNER — writes a series of distinct, verified video configs.
 *
 *   npm run plan:videos                      # video_002 … video_025 + long_05/10/15/20min
 *   npm run plan:videos -- --count 60 --start 2 --out videos
 *   npm run plan:videos -- --no-verify       # skip the "title promise" check (fast)
 *
 * Every Short is checked headlessly before it is written: the take must
 * deliver its title (CAUGHT → a catch, PERFECT RUN → no deaths …) and the
 * edit must land in 25–40 s. Long-form configs reference consecutive campaign
 * levels. An INDEX.md summarises the series.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { validateVideoConfig } from '../src/engine/video/VideoConfig';
import { resolveVideo } from '../src/engine/video/VideoSession';
import { campaignParams } from '../src/game/campaign';
import { registerContent } from '../src/game/content';
import { planSeries } from '../src/game/video/series';

const argv = process.argv.slice(2);
const arg = (k: string, d: string) => {
  const i = argv.indexOf(k);
  return i >= 0 ? argv[i + 1] : d;
};
const count = Number(arg('--count', '24'));
const start = Number(arg('--start', '2'));
const out = arg('--out', 'videos');
const verify = !argv.includes('--no-verify');
const longs = arg('--long', '5,10,15,20').split(',').filter(Boolean).map(Number);

registerContent();
const resolver = (c: Parameters<typeof resolveVideo>[0]) => resolveVideo(c, { campaign: (n) => campaignParams(n, c.enemy) });
mkdirSync(out, { recursive: true });
const t0 = Date.now();
const rows: string[] = [];
const series = planSeries(count, resolver, {
  startIndex: start,
  verify,
  onItem: (it, chk) => {
    const c = it.config;
    writeFileSync(join(out, `${c.id}.json`), JSON.stringify(c, null, 2) + '\n');
    const line = `| ${c.id} | ${c.title} | ${c.level} | ${c.scenario} | ${c.take} | ${c.character} | ${c.theme} | ${chk ? chk.duration.toFixed(1) : '?'} | ${chk?.ending ?? '?'} | ${chk?.deaths ?? '?'} |`;
    rows.push(line);
    console.log(`${c.id}  ${c.title.padEnd(36)} L${String(c.level).padStart(3)} ${c.scenario.padEnd(12)} take ${c.take} ${c.character.padEnd(8)} ${chk ? `${chk.duration.toFixed(1)} s ${chk.ending}` : ''}`);
  },
});
// long-form configs (rendered with `npm run record -- videos/long_10min.json`)
const longRows: string[] = [];
let level = 1;
for (const m of longs) {
  const id = `long_${String(m).padStart(2, '0')}min`;
  const cfg = { ...validateVideoConfig({ id, title: `Escape Factory — ${m} Minute Escape Marathon`, format: 'long', cameraStyle: 'dynamic', duration: m * 60, captions: [{ at: 0, duration: 3, text: 'CAN I SURVIVE THIS?!', style: 'hook' }], meta: { tags: ['escape factory', 'gameplay', 'obby', 'monster chase'], description: `${m} minutes of factory escapes: chases, near misses, fails and boss fights.` } }).config, long: { minutes: m, startLevel: level } };
  writeFileSync(join(out, `${id}.json`), JSON.stringify(cfg, null, 2) + '\n');
  longRows.push(`| ${id} | ${cfg.title} | ${m} min | from level ${level} |`);
  level += Math.max(4, Math.round(m * 1.6));
}
const index = `# Video series

Generated by \`npm run plan:videos\` (deterministic). Each Short was verified headlessly:
the take delivers what its title promises and the edit lands in 25–40 s.
Render with \`npm run record -- videos/<id>.json\` (or a whole folder).

| id | title | level | scenario | take | character | theme | duration (s) | ending | deaths |
|---|---|---|---|---|---|---|---|---|---|
| video_001 | Can I Escape The Factory? | 1 | CHASE | 1 | pip | FACTORY | 28.9 | finish | 0 |
${rows.join('\n')}

## Long videos (1920×1080)

| id | title | length | levels |
|---|---|---|---|
${longRows.join('\n')}
`;
writeFileSync(join(out, 'INDEX.md'), index);
console.log(`\n${series.length} shorts + ${longs.length} long configs in ${((Date.now() - t0) / 1000).toFixed(1)} s → ${out}/`);
if (series.length < count) {
  console.error(`only ${series.length}/${count} configs passed verification`);
  process.exit(1);
}
